#!/bin/bash
# Compute node: shared storage server (NFS), Slurm controller + slurmd, network mode switch. (as root)
#
# The compute node serves the shared file system so that the login node is an NFS *client*:
# a client does not receive inotify events for files created on another machine, as on Deucalion.
source /opt/testbed/guest/lib.sh
load_ips

log "shared storage: /srv/nfs/projects -> /projects, /srv/nfs/home-lisa -> /home/lisa"
mkdir -p /srv/nfs/projects /srv/nfs/home-lisa /projects /home/lisa
put_block /etc/fstab <<EOF
/srv/nfs/projects   /projects   none bind 0 0
/srv/nfs/home-lisa  /home/lisa  none bind 0 0
EOF
systemctl daemon-reload
mountpoint -q /projects || mount /projects
mountpoint -q /home/lisa || mount /home/lisa

log "home of lisa (shared): SSH key for the ssh -L / ssh -R checks and for Stage B"
if [ ! -f /home/lisa/.bashrc ]; then cp -a /etc/skel/. /home/lisa/; fi
mkdir -p /home/lisa/.ssh
install -m 600 "$TB/state/lisa_ed25519" /home/lisa/.ssh/id_ed25519
install -m 644 "$TB/state/lisa_ed25519.pub" /home/lisa/.ssh/id_ed25519.pub
cat "$TB/state/lisa_ed25519.pub" >/home/lisa/.ssh/authorized_keys
chmod 700 /home/lisa/.ssh; chmod 600 /home/lisa/.ssh/authorized_keys
chown -R lisa:lisa /home/lisa; chmod 755 /home/lisa

log "project directories"
mkdir -p "$PROJECT_DIR" /projects/.testbed/lisa /projects/.testbed/ino /projects/.testbed/rpms
chown lisa:lisa "$PROJECT_DIR" /projects/.testbed/lisa
chmod 1777 /projects/.testbed/ino

log "NFS exports for $SUBNET"
cat >/etc/exports <<EOF
/srv/nfs/projects   $SUBNET(rw,sync,no_subtree_check,no_root_squash)
/srv/nfs/home-lisa  $SUBNET(rw,sync,no_subtree_check,root_squash)
EOF
systemctl enable --now nfs-server
exportfs -ra

log "Slurm $SLURM_VERSION"
bash "$TB/guest/build-slurm.sh"
cp /opt/rpms/*.rpm /projects/.testbed/rpms/
V="$SLURM_VERSION"
dnf -y install /opt/rpms/slurm-"$V"-*.rpm /opt/rpms/slurm-perlapi-"$V"-*.rpm \
  /opt/rpms/slurm-slurmctld-"$V"-*.rpm /opt/rpms/slurm-slurmd-"$V"-*.rpm

CPUS="$(nproc)"
MEM_MB="$(awk '/MemTotal/ {print int($2/1024*0.85)}' /proc/meminfo)"
mkdir -p /etc/slurm /var/spool/slurmctld /var/spool/slurmd /var/log/slurm
chown slurm:slurm /var/spool/slurmctld /var/log/slurm
cat >/etc/slurm/slurm.conf <<EOF
# Generated by testbed. One compute node; its internet access is switched with './testbed net dev|normal'.
# proctrack/cgroup, as on Deucalion: a job's processes end with the job (the image mirror needs it).
ClusterName=testbed
SlurmctldHost=$CN_HOST
AuthType=auth/munge
SlurmUser=slurm
SlurmctldPidFile=/run/slurmctld/slurmctld.pid
SlurmdPidFile=/run/slurm/slurmd.pid
StateSaveLocation=/var/spool/slurmctld
SlurmdSpoolDir=/var/spool/slurmd
SlurmctldLogFile=/var/log/slurm/slurmctld.log
SlurmdLogFile=/var/log/slurm/slurmd.log
ProctrackType=proctrack/cgroup
TaskPlugin=task/none
SelectType=select/cons_tres
SelectTypeParameters=CR_Core_Memory
SchedulerType=sched/backfill
MpiDefault=none
ReturnToService=2
JobAcctGatherType=jobacct_gather/none
AccountingStorageType=accounting_storage/none
NodeName=cn NodeHostname=$CN_HOST NodeAddr=cn CPUs=$CPUS RealMemory=$MEM_MB State=UNKNOWN
PartitionName=arm Nodes=cn Default=YES MaxTime=INFINITE State=UP
EOF
cp /etc/slurm/slurm.conf /projects/.testbed/slurm.conf

log "chrony: the compute node takes its time from the login node (reachable in both modes)"
sed -i 's/^\(pool\|server\) /#&/' /etc/chrony.conf
put_block /etc/chrony.conf <<EOF
server login iburst
EOF
systemctl enable --now chronyd
systemctl restart chronyd

log "network mode switch (nftables), applied at every boot"
install -m 755 "$TB/guest/netmode.sh" /usr/local/sbin/testbed-netmode
cat >/etc/systemd/system/testbed-netmode.service <<EOF
[Unit]
Description=Testbed network mode (dev = internet, normal = cluster network only)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/testbed-netmode apply

[Install]
WantedBy=multi-user.target
EOF
[ -f /etc/testbed/netmode ] || echo dev >/etc/testbed/netmode
systemctl daemon-reload
systemctl enable testbed-netmode
# Load the rules now (dev mode) so connection tracking runs before any switch to normal.
/usr/local/sbin/testbed-netmode apply

log "starting Slurm"
systemctl enable --now slurmctld
systemctl restart slurmctld
systemctl enable --now slurmd
systemctl restart slurmd
sleep 3
scontrol update NodeName=cn State=RESUME 2>/dev/null || true
sinfo
log "compute node done"
